// Single definition of the browser bundle's composition. build.cjs signs and writes it;
// browser tests evaluate the same string, so tests always run what a release ships.
const fs=require('node:fs'),path=require('node:path');
const modules=['src/filters.js','src/player.js','src/player-ui.js','src/playback-power.js','src/plots.js','src/watch-history.js','src/next-episode.js','src/playback-exit.js','src/recommendation-cache.js'];
function appBundle(root){
  const read=file=>fs.readFileSync(path.join(root,file),'utf8');
  const version=JSON.parse(read('package.json')).version;
  return '/* FlixTor TV '+version+' · generated by node build.cjs */\nvar FTV_VERSION='+JSON.stringify(version)+';\nvar FTV_STYLE='+JSON.stringify(read('src/style.css'))+';\n'+modules.map(read).join('\n')+'\n'+read('src/app.js');
}
// The TV service (generated service.js) after its preamble: one definition for build.cjs and tests.
const serviceModules=['src/updater-service.js','src/remote-service.js','src/service.js'];
function serviceCode(root){const fs=require('node:fs'),path=require('node:path');return serviceModules.map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');}
function remoteTrust(root){const fs=require('node:fs'),path=require('node:path');const t=JSON.parse(fs.readFileSync(path.join(root,'remote-trust.json'),'utf8'));return {url:t.url,cas:t.cas};}
module.exports={appBundle,modules,serviceModules,serviceCode,remoteTrust};
